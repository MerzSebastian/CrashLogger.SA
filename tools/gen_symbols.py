#!/usr/bin/env python3
"""Generate gta_sa_1.0_us.symbols from C++ headers that document game functions.

Such headers describe game functions with comments such as

    // Converted from cdecl void CStreaming::RequestModel(int modelId, int flags) 0x4087E0
    /* Converted from thiscall void CPed::ProcessControl() 0x5E8CD0 */

This script scans a folder of such headers for those comments and writes one
"<address> <name>" line per function. Only names and addresses are extracted.

Usage:
    python tools/gen_symbols.py HEADER_DIR [-o OUTPUT]
"""
import argparse
import os
import re
import sys

LINE_RE = re.compile(
    r"(?://|/\*)\s*Converted from\s+\w+\s+(?P<sig>.*?)\s+(?P<addr>0x[0-9A-Fa-f]{5,8})\s*(?:\*/)?\s*$"
)
# The function name is the (possibly qualified) identifier right before the first '('.
NAME_RE = re.compile(r"((?:[~\w:<>]+::)?operator\s*[^\s(\w]+|[~\w:<>]+)\s*\(")


def parse_line(line):
    m = LINE_RE.search(line)
    if not m:
        return None
    n = NAME_RE.search(m.group("sig"))
    if not n:
        return None
    return int(m.group("addr"), 16), n.group(1)


def collect(root):
    found = {}
    for dirpath, _, files in os.walk(root):
        for f in files:
            if not f.endswith((".h", ".hpp", ".inl")):
                continue
            path = os.path.join(dirpath, f)
            with open(path, encoding="utf-8", errors="replace") as fh:
                for line in fh:
                    r = parse_line(line)
                    if r and r[0] not in found:
                        found[r[0]] = r[1]
    return found


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("header_dir", help="folder with headers that document game functions")
    ap.add_argument("-o", "--output", default="data/gta_sa_1.0_us.symbols")
    args = ap.parse_args()

    if not os.path.isdir(args.header_dir):
        sys.exit(f"not a directory: {args.header_dir}")
    symbols = collect(args.header_dir)
    if not symbols:
        sys.exit("no 'Converted from ... 0xADDR' comments found; is this a folder with such headers?")

    with open(args.output, "w", encoding="utf-8", newline="\n") as out:
        out.write("# GTA San Andreas 1.0 US function addresses (generated by tools/gen_symbols.py)\n")
        out.write("# Format: <address> <name>\n")
        for addr in sorted(symbols):
            out.write(f"0x{addr:08X} {symbols[addr]}\n")
    print(f"wrote {len(symbols)} symbols to {args.output}")


if __name__ == "__main__":
    main()
